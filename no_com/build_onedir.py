HERE = os.path.dirname(os.path.abspath(__file__))
APP_KEYS = ("launcher", "quote", "esign", "search", "csp")


def _split_args(argv):
    """명령줄을 (일반 인자들, --app 값) 으로 나눈다. --app 이 없으면 '' (전체 빌드)."""
    rest, only, i = [], "", 0
    while i < len(argv):
        a = argv[i]
        if a == "--app":
            only = argv[i + 1].strip().lower() if i + 1 < len(argv) else ""
            i += 2
            continue
        if a.startswith("--app="):
            only = a.split("=", 1)[1].strip().lower()
        elif a != "--single":          # 예전 옵션 — 지금은 뜻이 없어 무시한다
            rest.append(a)
        i += 1
    if only and only not in APP_KEYS:
        print(f"오류: --app 에는 {', '.join(APP_KEYS)} 중 하나를 쓰세요. (받은 값: {only})")
        sys.exit(1)
    return rest, only


def _get_args():
    args, only = _split_args(sys.argv[1:])
    if args:
        app_name = args[0].strip()
        icon     = args[1].strip() if len(args) >= 2 else ""
    else:
        app_name = input("프로세스명(EXE 파일명, 예: 견적자동화): ").strip()
        icon     = input("아이콘 경로 (없으면 엔터): ").strip()

    if not app_name:
        print("오류: 이름을 입력하세요.")
        sys.exit(1)

    if icon and not os.path.isabs(icon):
        icon = os.path.join(HERE, icon)
    if icon and os.path.isdir(icon):
        print(f"경고: 아이콘 경로가 디렉터리입니다 — {icon}")
        icon = ""
    if icon and not os.path.isfile(icon):
        print(f"경고: 아이콘 파일 없음 — {icon}")
        icon = ""
    if icon and not icon.lower().endswith(".ico"):
        print(f"경고: .ico 파일이 아닙니다 — {icon}")
        icon = ""

    return app_name, icon, only


