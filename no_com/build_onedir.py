"""
build_onedir.py
===============
no_com/ 앱을 onedir 형태로 빌드하는 스크립트.
Python 미설치 환경에서도 동작 (Python 인터프리터 포함).

사용법
------
  python build_onedir.py                # 이름 프롬프트
  python build_onedir.py 견적자동화 --single   # exe 1개(해시 1개)로 전부 포함
  python build_onedir.py 견적자동화     # → dist/견적자동화/견적자동화.exe (런처)
                                        #    + 견적자동화_quote/_esign/_search/_csp.exe
  python build_onedir.py 견적자동화 icon.ico

배포 방법
---------
  dist/견적자동화-install/ 폴더 전체를 공유 폴더에 게시.
  각 PC에서 Install.cmd 로 로컬 설치 후 바탕화면 QuoteAuto 바로가기로 실행.
  업데이트도 같은 설치 절차를 사용하며, 평소 실행은 공유 배포본을 읽지 않는다.
"""

