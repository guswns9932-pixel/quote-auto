def _make_spec(app_name: str, icon: str, only: str = "") -> str:
    """PyInstaller spec 을 만든다. only 가 비어 있으면 전체, 앱 이름이면 그 앱만."""
    return (_SPEC_TEMPLATE
            .replace("@HERE@", HERE)
            .replace("@APP_NAME@", app_name)
            .replace("@ICON@", icon)
            .replace("@ONLY@", only))


def output_names(app_name: str, only: str = ""):
    """(만들어지는 폴더 이름, 그 안의 exe 이름들)."""
    exes = {"launcher": app_name, **{k: f"{app_name}_{k}" for k in APP_KEYS if k != "launcher"}}
    if only:
        return exes[only], [exes[only] + ".exe"]
    return app_name, [exes[k] + ".exe" for k in APP_KEYS]


def _create_icon() -> str:
    """PIL로 견적·전자서명 앱에 어울리는 아이콘을 코드로 생성해 icon.ico 경로를 반환한다."""
    try:
        from PIL import Image, ImageDraw
    except ImportError:
        print("경고: Pillow 미설치 — 아이콘 없이 빌드합니다.")
        return ""
    except Exception as e:
        print(f"경고: Pillow 초기화 오류 ({e}) — 아이콘 없이 빌드합니다.")
        return ""

    out_path = os.path.join(HERE, "icon.ico")
    sizes = [256, 128, 64, 48, 32, 24, 16]
    images = []

    for sz in sizes:
        img = Image.new("RGBA", (sz, sz), (0, 0, 0, 0))
        draw = ImageDraw.Draw(img)

        # ── 배경: 파란 둥근 사각형 ──────────────────────────────
        BG  = (21, 101, 192, 255)   # #1565C0
        PAD = max(1, sz // 16)
        R   = max(2, sz // 8)
        try:
            # rounded_rectangle: Pillow 8.2.0+
            draw.rounded_rectangle([PAD, PAD, sz - PAD - 1, sz - PAD - 1],
                                   radius=R, fill=BG)
        except AttributeError:
            draw.rectangle([PAD, PAD, sz - PAD - 1, sz - PAD - 1], fill=BG)

        # ── 문서 몸체 (흰색 사각형, 우상단 모서리 접힘) ──────────
        DX   = sz * 0.20
        DY   = sz * 0.14
        DW   = sz * 0.60
        DH   = sz * 0.72
        FOLD = sz * 0.15          # 접힌 삼각형 크기
        DOC  = (255, 255, 255, 255)
        # 접힘 다각형: 우상단 모서리 제외 5꼭짓점
        poly = [
            (DX,          DY),
            (DX + DW - FOLD, DY),
            (DX + DW,    DY + FOLD),
            (DX + DW,    DY + DH),
            (DX,          DY + DH),
        ]
        draw.polygon(poly, fill=DOC)

        # 접힘 삼각형 음영 (연한 회색)
        SHADOW = (200, 210, 230, 255)
        fold_tri = [
            (DX + DW - FOLD, DY),
            (DX + DW,        DY + FOLD),
            (DX + DW - FOLD, DY + FOLD),
        ]
        draw.polygon(fold_tri, fill=SHADOW)

        # ── 문서 안 텍스트 줄 (파란 가로선) ─────────────────────
        LINE_CLR = (21, 101, 192, 200)
        lx0  = DX + sz * 0.07
        lx1  = DX + DW - sz * 0.07
        ly   = DY + FOLD + sz * 0.07
        step = sz * 0.10
        lw   = max(1, sz // 48)
        for i in range(4):
            y = ly + i * step
            # 마지막 줄 오른쪽은 짧게 (줄 끝 느낌)
            rx = lx1 if i < 3 else lx0 + (lx1 - lx0) * 0.55
            draw.rectangle([lx0, y, rx, y + lw], fill=LINE_CLR)

        # ── 서명 곡선 (사인파 형태) ──────────────────────────────
        SIG  = (255, 193, 7, 255)   # 노란빛 금색
        SX   = DX + sz * 0.07
        SEW  = DX + DW - sz * 0.09
        SY   = DY + DH - sz * 0.14
        AMP  = sz * 0.04
        slw  = max(1, sz // 32)
        pts  = []
        steps = max(20, sz // 4)
        for s in range(steps + 1):
            t = s / steps
            x = SX + t * (SEW - SX)
            y = SY + math.sin(t * math.pi * 3) * AMP
            pts.append((x, y))
        for i in range(len(pts) - 1):
            x0, y0 = pts[i]
            x1, y1 = pts[i + 1]
            draw.line([x0, y0, x1, y1], fill=SIG, width=slw)

        images.append(img)

    try:
        images[0].save(out_path, format="ICO", append_images=images[1:],
                       sizes=[(s, s) for s in sizes])
    except Exception as e:
        print(f"경고: 아이콘 저장 실패 ({e}) — 아이콘 없이 빌드합니다.")
        return ""
    print(f"  아이콘 생성 : {out_path}")
    return out_path


def main():
    app_name, icon, only = _get_args()

    if not icon:
        try:
            icon = _create_icon()
        except Exception as e:
            print(f"경고: 아이콘 생성 중 오류 ({e}) — 아이콘 없이 빌드합니다.")
            icon = ""
    # 최종 안전 검사: 디렉터리나 비.ico 파일이 들어오면 제거
    if icon and not (os.path.isfile(icon) and icon.lower().endswith(".ico")):
        print(f"경고: 유효하지 않은 아이콘 경로 제거 — {icon}")
        icon = ""

    spec_path = os.path.join(HERE, f"_build_{app_name}.spec")
    dist_dir  = os.path.join(HERE, "dist")
    work_dir  = os.path.join(HERE, "build")

    with open(spec_path, "w", encoding="utf-8") as f:
        f.write(_make_spec(app_name, icon, only))
    out_name, exe_names = output_names(app_name, only)

    log_path = os.path.join(HERE, f"_build_{app_name}.log")
    cmd = [
        sys.executable, "-m", "PyInstaller",
        spec_path,
        "--distpath", dist_dir,
        "--workpath", work_dir,
        "--noconfirm",
        "--clean",
    ]

    print(f"\n{'='*54}")
    print(f"  앱 이름 : {app_name}")
    print(f"  아이콘  : {icon or '없음'}")
    print(f"  대상    : {only or '전체 (런처 + 앱 4개)'}")
    print(f"  출력    : {os.path.join(dist_dir, out_name)}/")
    print(f"  로그    : {log_path}")
    print(f"{'='*54}")
    print("  빌드 진행 중 (수 분 소요)...\n")

    # 콘솔 실시간 출력 + 로그 파일 동시 저장 (tee)
    returncode = 1
    try:
        proc = subprocess.Popen(
            cmd, cwd=HERE,
            stdout=subprocess.PIPE,
            stderr=subprocess.STDOUT,
            text=True, encoding="utf-8", errors="replace",
        )
        with open(log_path, "w", encoding="utf-8") as log_f:
            for line in proc.stdout:
                sys.stdout.write(line)
                sys.stdout.flush()
                log_f.write(line)
        proc.wait()
        returncode = proc.returncode
    except Exception as e:
        print(f"\n빌드 실행 오류: {e}")

    try:
        os.remove(spec_path)
    except OSError:
        pass

    if returncode == 0:
        out_dir = os.path.join(dist_dir, out_name)
        size_mb = sum(
            os.path.getsize(os.path.join(r, f))
            for r, _, fs in os.walk(out_dir) for f in fs
        ) / 1024 / 1024
        print(f"\n{'='*54}")
        print(f"  완료  : {out_dir}")
        print(f"  크기  : {size_mb:.1f} MB (폴더 전체)")
        print()
        print(f"  배포  : dist/{out_name}/ 폴더 전체를 압축해서 전달")
        print(f"  실행  : {exe_names[0]} 더블클릭 (Python 불필요)")
        print(f"  인가  : exe {len(exe_names)}개 해시 제출 — {', '.join(exe_names)}")
        print(f"{'='*54}\n")
    else:
        print(f"\n빌드 실패 (exit code={returncode})")
        print(f"  오류 로그: {log_path}")
        print(f"  로그 파일을 열어 ERROR / CRITICAL 메시지를 확인하세요.")

    sys.exit(returncode)


